/**
 * GUCDI — deterministic LCR app generator (pure). The final scaffolding pass of
 * the whole-app `vibe`: turns the LCR plan (routes + personas) into a RUNNABLE,
 * NAVIGABLE Vite/React app — the scaffold (package.json, vite, tailwind v4) + the
 * router (every declared surface reachable, no auth walls) + the persona shell
 * (chrome-aware nav + persona/theme switcher) + a stub page per route (sets the
 * `@story` marker, shows the surface's personas/states). No LLM: the SKELETON is
 * deterministic from the plan; the LLM `vibe surfaces` pass later replaces each
 * stub's body with the designed UI (rendering via the queries.ts adaptor).
 *
 * Returns a list of files; the IO (writing them) is in index.ts. See
 * docs/plans/vibe-whole-mock-lcr.md.
 */
import type { LcrPlan } from "./lcr-plan.js";

export interface GenFile {
  /** path relative to the mock root (e.g. "src/App.tsx"), except mockYaml. */
  path: string;
  content: string;
}

/** route → React component name: "/admin/workers" → "AdminWorkersPage", "/" → "HomePage". */
export function routeToName(route: string): string {
  const name = route
    .split("/")
    .filter(Boolean)
    .filter((s) => !s.startsWith(":"))
    .map((s) =>
      s
        .replace(/[^a-zA-Z0-9]+/g, " ")
        .trim()
        .split(/\s+/)
        .map((w) => (w ? w[0]!.toUpperCase() + w.slice(1) : ""))
        .join("")
    )
    .join("");
  return (name || "Home") + "Page";
}

interface RouteEntry {
  route: string;
  component: string;
  personas: string[];
  stories: string[];
  states: string[];
  home: boolean;
}

/** Group surfaces by unique route + assign collision-free component names. */
function routeEntries(plan: LcrPlan): RouteEntry[] {
  const byRoute = new Map<string, RouteEntry>();
  for (const s of plan.surfaces) {
    let e = byRoute.get(s.route);
    if (!e) {
      e = { route: s.route, component: "", personas: [], stories: [], states: [], home: false };
      byRoute.set(s.route, e);
    }
    if (!e.personas.includes(s.persona)) e.personas.push(s.persona);
    if (!e.stories.includes(s.storyId)) e.stories.push(s.storyId);
    for (const st of s.states) if (!e.states.includes(st)) e.states.push(st);
    if (s.home) e.home = true;
  }
  const used = new Set<string>();
  for (const e of byRoute.values()) {
    let name = routeToName(e.route);
    if (used.has(name)) {
      let i = 2;
      while (used.has(`${name.replace(/Page$/, "")}${i}Page`)) i++;
      name = `${name.replace(/Page$/, "")}${i}Page`;
    }
    used.add(name);
    e.component = name;
  }
  return [...byRoute.values()];
}

