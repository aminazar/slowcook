function useStoryMarker(): string {
  return `import { useEffect } from "react";

/** Sets document.documentElement.dataset.slowcookStory so the review overlay can
 *  attribute LCR comments to the right story (the runtime @story marker). */
export function useStoryMarker(storyId: string): void {
  useEffect(() => {
    const prev = document.documentElement.dataset.slowcookStory;
    document.documentElement.dataset.slowcookStory = storyId;
    return () => {
      if (prev) document.documentElement.dataset.slowcookStory = prev;
      else delete document.documentElement.dataset.slowcookStory;
    };
  }, [storyId]);
}
`;
}

function personasTs(plan: LcrPlan): string {
  const personas = plan.personas.map((p) => {
    const surfaces = plan.surfaces.filter((s) => s.persona === p.id);
    const home = surfaces.find((s) => s.home)?.route ?? surfaces[0]?.route ?? "/";
    return {
      id: p.id,
      chrome: p.chrome ?? "member",
      home,
      routes: [...new Set(surfaces.map((s) => s.route))],
    };
  });
  return `// Persona registry — derived from the LCR plan by \`slowcook vibe app\`.
export interface Persona { id: string; chrome: "member" | "public" | "admin"; home: string; routes: string[] }
export const PERSONAS: Persona[] = ${j(personas, null, 2)};
`;
}

function shellTsx(): string {
  return `import { useState } from "react";
import { Link, Outlet, useLocation } from "react-router-dom";
import { PERSONAS } from "./personas";

/** The LCR shell: a chrome-aware nav for the active persona + a persona/theme
 *  switcher. Every route stays reachable (the full route list is always linked),
 *  so reviewers can navigate the whole app without auth walls. */
export function Shell() {
  const [persona, setPersona] = useState(PERSONAS[0]?.id ?? "");
  const [theme, setTheme] = useState<"dark" | "day">("dark");
  const active = PERSONAS.find((p) => p.id === persona) ?? PERSONAS[0];
  const loc = useLocation();

  function toggleTheme() {
    const next = theme === "dark" ? "day" : "dark";
    setTheme(next);
    document.documentElement.dataset.theme = next;
  }

  return (
    <div style={{ display: "flex", minHeight: "100vh" }}>
      <aside style={{ width: 248, borderRight: "1px solid var(--color-border)", padding: 16, boxSizing: "border-box" }}>
        <div style={{ fontWeight: 800, marginBottom: 12 }}>LCR · review</div>
        <label style={{ fontSize: 12, opacity: 0.7 }}>Viewing as</label>
        <select value={persona} onChange={(e) => setPersona(e.target.value)} style={{ width: "100%", margin: "6px 0 14px", padding: 6 }}>
          {PERSONAS.map((p) => (
            <option key={p.id} value={p.id}>{p.id} ({p.chrome})</option>
          ))}
        </select>
        <button onClick={toggleTheme} style={{ marginBottom: 16, padding: "4px 10px" }}>{theme === "dark" ? "☾ dark" : "☀ day"}</button>
        <nav style={{ display: "flex", flexDirection: "column", gap: 4 }}>
          <div style={{ fontSize: 11, textTransform: "uppercase", opacity: 0.6, margin: "8px 0 2px" }}>{active?.id} surfaces</div>
          {(active?.routes ?? []).map((r) => (
            <Link key={r} to={r} style={{ color: loc.pathname === r ? "var(--color-brand)" : "var(--color-text)", textDecoration: "none", padding: "2px 0" }}>{r}</Link>
          ))}
        </nav>
      </aside>
      <main style={{ flex: 1, padding: 24 }}>
        <Outlet />
      </main>
    </div>
  );
}
`;
}

function pageStub(e: RouteEntry): string {
  const story = e.stories[0] ?? "";
  return `import { useStoryMarker } from "../shell/useStoryMarker";

// @story ${e.stories.map((s) => `story-${s}`).join(", ")}
// STUB — generated by \`slowcook vibe app\`. The page body is a placeholder;
// \`slowcook vibe surfaces\` replaces it with the designed UI rendering via
// ../lib/queries. The route, persona shell, and @story marker are real.
export function ${e.component}() {
  useStoryMarker(${j(story)});
  return (
    <section>
      <h1 style={{ marginTop: 0 }}>${e.route}</h1>
      <p style={{ opacity: 0.7 }}>
        persona: ${e.personas.join(", ")} · story: ${e.stories.map((s) => `story-${s}`).join(", ")}${e.home ? " · home" : ""}
      </p>
      <p style={{ opacity: 0.7 }}>states to cover: ${e.states.length ? e.states.join(", ") : "(none declared)"}</p>
      <div style={{ marginTop: 16, padding: 16, border: "1px dashed var(--color-border)", borderRadius: 8 }}>
        ▢ page body — run <code>slowcook vibe surfaces</code> to generate the UI (renders via the SQLite data adaptor in <code>../lib/queries</code>).
      </div>
    </section>
  );
}
`;
}

function appTsx(entries: RouteEntry[]): string {
  const imports = entries.map((e) => `import { ${e.component} } from "./pages/${e.component}";`).join("\n");
  const routes = entries
    .map((e) => `        <Route path=${j(e.route)} element={<${e.component} />} />`)
    .join("\n");
  const homeRoute = entries.find((e) => e.home)?.route ?? entries[0]?.route ?? "/";
  return `import { HashRouter, Routes, Route, Navigate } from "react-router-dom";
import { Shell } from "./shell/Shell";
${imports}

// LCR app — generated by \`slowcook vibe app\`. Every declared surface is a route;
// no auth guards (barrier-free review). HashRouter keeps it static-deployable.
export function App() {
  return (
    <HashRouter>
      <Routes>
        <Route element={<Shell />}>
${routes}
          <Route path="/" element={<Navigate to=${j(homeRoute)} replace />} />
        </Route>
      </Routes>
    </HashRouter>
  );
}
`;
}

