/** route → React component name: "/admin/workers" → "AdminWorkersPage", "/" → "HomePage". */
export function routeToName(route: string): string {
  const pascal = (raw: string) =>
    raw
      .replace(/[^a-zA-Z0-9]+/g, " ")
      .trim()
      .split(/\s+/)
      .map((w) => (w ? w[0]!.toUpperCase() + w.slice(1) : ""))
      .join("");
  // Keep param segments as `By<Param>` so `/projects/:projectId` →
  // `ProjectsByProjectIdPage`, not a meaningless `Projects2Page` collision.
  const name = route
    .split("/")
    .filter(Boolean)
    .map((s) => (s.startsWith(":") ? "By" + pascal(s.slice(1)) : pascal(s)))
    .join("");
  return (name || "Home") + "Page";
}

interface RouteEntry {
  route: string;
  component: string;
  personas: string[];
  stories: string[];
  states: string[];
  home: boolean;
}

/** Group surfaces by unique route + assign collision-free component names. */
function routeEntries(plan: LcrPlan): RouteEntry[] {
  const byRoute = new Map<string, RouteEntry>();
  for (const s of plan.surfaces) {
    let e = byRoute.get(s.route);
    if (!e) {
      e = { route: s.route, component: "", personas: [], stories: [], states: [], home: false };
      byRoute.set(s.route, e);
    }
    if (!e.personas.includes(s.persona)) e.personas.push(s.persona);
    if (!e.stories.includes(s.storyId)) e.stories.push(s.storyId);
    for (const st of s.states) if (!e.states.includes(st)) e.states.push(st);
    if (s.home) e.home = true;
  }
  const used = new Set<string>();
  for (const e of byRoute.values()) {
    let name = routeToName(e.route);
    if (used.has(name)) {
      let i = 2;
      while (used.has(`${name.replace(/Page$/, "")}${i}Page`)) i++;
      name = `${name.replace(/Page$/, "")}${i}Page`;
    }
    used.add(name);
    e.component = name;
  }
  return [...byRoute.values()];
}

