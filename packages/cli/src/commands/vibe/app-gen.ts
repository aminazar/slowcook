/** Slug arbitrary text into a stable id segment for the EPSS manifest. */
function textSlug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 48) || "x";
}

